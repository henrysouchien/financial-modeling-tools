def _template_seed_values(item_ids: tuple[str, ...]) -> dict[str, float]:
    """Seed values derived from the checked-in generic template artifact.

    The checked-in artifact (schema/templates/sia_generic.json, regenerated by
    schema/templates/template_builder.py) owns these defaults. A workbook row
    still carrying its seed value with no sourced provenance is a legacy
    placeholder. A missing row or non-constant seed raises loudly instead of
    silently weakening placeholder detection.
    """

    from .templates import load_sia_generic_template

    model = load_sia_generic_template()
    model.build_index()
    seeds: dict[str, float] = {}
    for item_id in item_ids:
        try:
            item = model._index[item_id]
        except KeyError as exc:
            # This runs at import, and ``import schema`` reaches this module, so
            # a bare KeyError here is a bootstrap failure with no explanation.
            # The usual cause is an intermediate artifact: the two-stage
            # template regeneration writes a Valuation-less workbook between
            # its two commands, and anything importing ``schema`` in between
            # lands right here.  See docs/reference/financial-modeling-studio.md.
            raise ValueError(
                f"template seed row {item_id!r} is absent from the checked-in "
                "generic template; the artifact is incomplete (a Valuation-less "
                "intermediate from two-stage regeneration will look like this)"
            ) from exc
        values = {
            cell.value
            for cell in (item.values.values if item.values is not None else {}).values()
            if cell.value is not None
        }
        if len(values) != 1:
            raise ValueError(
                f"template seed for {item_id!r} is not a single constant: {sorted(values)!r}"
            )
        seeds[item_id] = float(next(iter(values)))
    return seeds


_VALUATION_PLACEHOLDER_VALUES = _template_seed_values(
    (
        "tpl.v.current_valuation.stock_price",
        "tpl.v.cost_of_equity.risk_free_rate",
        "tpl.v.cost_of_equity.equity_risk_premium",
        "tpl.v.cost_of_equity.raw_beta",
        "tpl.v.cost_of_equity.beta_floor",
        "tpl.v.wacc.sofr_rate",
        "tpl.v.wacc.credit_spread",
    )
)
_MARKET_BETA_ANCHOR = 1.0


class ValuationInputReadinessFlag(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    code: str
    severity: ValuationInputReadinessSeverity
    message: str | None = None


class ValuationInputReadiness(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    status: ValuationInputReadinessStatus = "incomplete"
    populated: list[str] = Field(default_factory=list)
    missing: list[str] = Field(default_factory=list)
    sources: dict[str, str] = Field(default_factory=dict)
    flags: list[ValuationInputReadinessFlag] = Field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return self.model_dump(mode="json")




def compute_valuation_input_readiness(
    model: FinancialModel,
    *,
    computed_values: ComputedValues | None = None,
) -> ValuationInputReadiness:
    """Return deterministic valuation-input completeness from model row readback."""

    model.build_index()
    computed_values_fn = _computed_values
    normalize_computed_values_fn = _normalize_computed_values
    latest_numeric_value_fn = _latest_numeric_value
    nearly_equal_fn = _nearly_equal
    values = normalize_computed_values_fn(
        computed_values if computed_values is not None else computed_values_fn(model)
    )
    populated: list[str] = []
    missing: list[str] = []
    sources: dict[str, str] = {}
    has_legacy_placeholder = False
    economic_inputs = _VALUATION_ECONOMIC_INPUTS
    required_inputs = _VALUATION_REQUIRED_INPUTS
    placeholder_values = _VALUATION_PLACEHOLDER_VALUES
    market_beta_anchor = _MARKET_BETA_ANCHOR

    for field in required_inputs:
        item_id = economic_inputs[field]
        value = latest_numeric_value_fn(values.get(item_id, {}))
        if value is None:
            missing.append(field)
        else:
            populated.append(field)
            sources[field] = "workbook_readback"

    for item_id, placeholder_value in placeholder_values.items():
        value = latest_numeric_value_fn(values.get(item_id, {}))
        item = model._index.get(item_id)
        has_sourced_provenance = bool(
            item is not None
            and item.values is not None
            and any(
                cell.value is not None
                and str(cell.provenance.value) in {"imported_vendor", "derived"}
                for cell in item.values.values.values()
            )
        )
        if (
            not has_sourced_provenance
            and nearly_equal_fn(value, placeholder_value, tolerance=1e-12)
        ):
            has_legacy_placeholder = True
            break

    raw_beta = latest_numeric_value_fn(values.get(economic_inputs["raw_beta"], {}))
    adjusted_beta = latest_numeric_value_fn(values.get(economic_inputs["adjusted_beta"], {}))
    if (
        not any(
            cell.value is not None and cell.provenance.value == "imported_vendor"
            for item_id in (
                economic_inputs["raw_beta"],
                economic_inputs["adjusted_beta"],
            )
            for item_values in (
                model._index[item_id].values if item_id in model._index else None,
            )
            for cell in (
                item_values.values.values() if item_values is not None else ()
            )
        )
        and
        nearly_equal_fn(raw_beta, placeholder_values["tpl.v.cost_of_equity.raw_beta"], tolerance=1e-12)
        and nearly_equal_fn(adjusted_beta, market_beta_anchor, tolerance=1e-12)
    ):
        has_legacy_placeholder = True

    flag_model = ValuationInputReadinessFlag
    flags: list[ValuationInputReadinessFlag] = []
    if missing:
        flags.append(
            flag_model(
                code="valuation_inputs_missing",
                severity="warning",
                message=(
                    "One or more required valuation input rows are blank; do not "
                    "treat DCF/WACC outputs as clean until the inputs are sourced."
                ),
            )
        )
    if has_legacy_placeholder:
        flags.append(
            flag_model(
                code="legacy_valuation_placeholders_present",
                severity="warning",
                message=(
                    "One or more valuation input rows match legacy template "
                    "placeholder values; treat them as stale or ambiguous unless "
                    "independently sourced."
                ),
            )
        )

    readiness_model = ValuationInputReadiness
    return readiness_model(
        status="complete" if not missing and not has_legacy_placeholder else "incomplete",
        populated=populated,
        missing=missing,
        sources=sources,
        flags=flags,
    )


def _valuation_input_status(
    readiness: ValuationInputReadiness | dict[str, Any] | None,
) -> tuple[str | None, list[str]]:
    if readiness is None:
        return None, []
    if isinstance(readiness, dict):
        status = readiness.get("status")
        missing = readiness.get("missing") or []
    else:
        status = readiness.status
        missing = readiness.missing
    return str(status) if status is not None else None, [str(item) for item in missing]


